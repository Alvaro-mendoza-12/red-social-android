'use strict'
const {test}=require('node:test')
const assert=require('node:assert/strict')
const {randomUUID}=require('node:crypto')
const domain=require('../src/purpose-domain')
const {projectGame}=require('../src/purpose-routes')
const A=randomUUID(),B=randomUUID(),C=randomUUID(),POST=randomUUID(),REF=randomUUID()
const NOW='2026-11-04T22:00:00.000Z',START='2026-11-05T00:00:00.000Z'
const envelope=(action,extra={})=>({action,operationId:randomUUID(),expectedRevision:0,...extra})
const gameContext=actorId=>({actorId,participants:[{id:A,name:'Ana'},{id:B,name:'Bruno'}],gameIds:new Set(['chess'])})
const proposal=()=>domain.gamingCommand(envelope('propose',{gameId:'chess',objective:'Practicar aperturas',durationMinutes:45,startsAt:START}))
test('only the post author can conclude with currently available references, and withdrawal removes the old conclusion',()=>{
  const context={actorId:A,isAuthor:true,postId:POST,contributionIds:new Set([REF])}
  const open=domain.changeSocial(null,domain.socialCommand(envelope('start')),context,NOW)
  assert.equal(open.status,'open')
  assert.throws(()=>domain.changeSocial(open,domain.socialCommand(envelope('conclude',{conclusion:'Gracias',contributionIds:[REF]})),{...context,isAuthor:false},NOW),{code:'PURPOSE_AUTHOR_REQUIRED'})
  assert.throws(()=>domain.changeSocial(open,domain.socialCommand(envelope('conclude',{conclusion:'Gracias',contributionIds:[randomUUID()]})),context,NOW),{code:'PURPOSE_REFERENCE_UNAVAILABLE'})
  const done=domain.changeSocial(open,domain.socialCommand(envelope('conclude',{conclusion:'La segunda opción resolvió la petición.',contributionIds:[REF,REF]})),context,NOW)
  assert.deepEqual(done.contributionIds,[REF]);assert.equal(open.status,'open')
  const withdrawn=domain.changeSocial(done,domain.socialCommand(envelope('retract')),context,NOW)
  assert.equal(withdrawn.status,'withdrawn');assert.equal(withdrawn.conclusion,'');assert.deepEqual(withdrawn.contributionIds,[])
})
test('replanning resets consent and reconfirmation; one actor cannot accept for the other',()=>{
  let state=domain.changeGaming(null,proposal(),gameContext(A),NOW)
  assert.equal(domain.gamingStatus(state,NOW),'pending')
  state=domain.changeGaming(state,{action:'accept'},gameContext(A),NOW)
  state=domain.changeGaming(state,{action:'accept'},gameContext(A),NOW)
  assert.equal(domain.gamingStatus(state,NOW),'pending')
  state=domain.changeGaming(state,{action:'accept'},gameContext(B),NOW)
  assert.equal(domain.gamingStatus(state,NOW),'agreed')
  assert.throws(()=>domain.changeGaming(state,{action:'confirm'},gameContext(A),NOW),{code:'PURPOSE_RECONFIRM_UNAVAILABLE'})
  state=domain.changeGaming(state,{action:'confirm'},gameContext(A),'2026-11-04T23:30:00Z')
  state=domain.changeGaming(state,{action:'confirm'},gameContext(B),'2026-11-04T23:30:00Z')
  assert.equal(domain.gamingStatus(state,'2026-11-04T23:30:00Z'),'ready')
  assert.throws(()=>domain.changeGaming(state,{...proposal(),action:'replan'},gameContext(B),NOW),{code:'PURPOSE_AUTHOR_REQUIRED'})
  state=domain.changeGaming(state,{...proposal(),action:'replan'},gameContext(A),NOW)
  assert.equal(state.planRevision,2);assert.deepEqual(state.accepted,{});assert.deepEqual(state.confirmed,{})
})
test('expired plans reject consent, cancellation is explicit, and feedback stays private to its actor',()=>{
  let state=domain.changeGaming(null,proposal(),gameContext(A),NOW)
  assert.equal(domain.gamingStatus(state,'2026-11-05T00:11:00Z'),'expired')
  assert.throws(()=>domain.changeGaming(state,{action:'accept'},gameContext(B),'2026-11-05T00:11:00Z'),{code:'PURPOSE_PLAN_EXPIRED'})
  assert.throws(()=>domain.changeGaming(state,{action:'accept'},gameContext(C),NOW),{code:'PURPOSE_ACCESS_DENIED'})
  assert.throws(()=>domain.changeGaming(state,{action:'feedback',outcome:'played'},gameContext(A),NOW),{code:'PURPOSE_TOO_EARLY'})
  state=domain.changeGaming(state,{action:'feedback',outcome:'played'},gameContext(A),'2026-11-05T01:00:00Z')
  assert.equal(projectGame(state,A).myOutcome,'played');assert.equal(projectGame(state,B).myOutcome,null)
  assert.equal(Object.hasOwn(projectGame(state,B),'outcomes'),false)
  state=domain.changeGaming(state,{action:'decline'},gameContext(B),NOW)
  assert.equal(domain.gamingStatus(state,NOW),'cancelled')
})
test('guide availability requires an explicit bounded offer and can be withdrawn',()=>{
  const context={actorId:A,communityId:POST}
  const offered=domain.changeGuide(null,domain.guideCommand(envelope('offer',{hours:2})),context,NOW)
  assert.equal(offered.expiresAt,'2026-11-05T00:00:00.000Z');assert.equal(offered.active,true)
  assert.equal(domain.changeGuide(offered,domain.guideCommand(envelope('withdraw')),context,NOW).active,false)
  assert.throws(()=>domain.guideCommand(envelope('offer',{hours:25})),{code:'PURPOSE_DURATION_INVALID'})
})
test('opening a destination is distinct from reporting a contribution, including after its event has ended',()=>{
  const context={actorId:A,communityId:POST,targets:new Set([`event:${REF}`])}
  let state=domain.changeStart(null,domain.startCommand(envelope('select',{targetKind:'event',targetId:REF})),context,NOW)
  assert.equal(state.opened,false);assert.equal(state.outcome,null)
  state=domain.changeStart(state,{action:'opened'},context,NOW)
  assert.equal(state.opened,true);assert.equal(state.outcome,null)
  assert.throws(()=>domain.changeStart(state,{action:'opened'},{...context,targets:new Set()},NOW),{code:'PURPOSE_REFERENCE_UNAVAILABLE'})
  state=domain.changeStart(state,{action:'report',outcome:'participated'},{...context,targets:new Set()},NOW)
  assert.equal(state.outcome,'participated')
  assert.throws(()=>domain.changeStart(state,{action:'report',outcome:'received_help'},context,NOW),{code:'PURPOSE_OUTCOME_INVALID'})
})
test('commands reject oversized references, text, dates and guessed operation identifiers',()=>{
  assert.throws(()=>domain.socialCommand(envelope('conclude',{conclusion:'x',contributionIds:Array(6).fill(REF)})),{code:'PURPOSE_REFERENCES_LIMIT'})
  assert.throws(()=>domain.socialCommand(envelope('conclude',{conclusion:'x'.repeat(801),contributionIds:[]})),{code:'PURPOSE_TEXT_LIMIT'})
  assert.throws(()=>domain.socialCommand(envelope('start',{operationId:'not-an-id'})),{code:'PURPOSE_INVALID_ID'})
  assert.throws(()=>domain.changeGaming(null,{...proposal(),startsAt:'2026-11-04T22:05:00Z'},gameContext(A),NOW),{code:'PURPOSE_DATE_INVALID'})
  assert.throws(()=>domain.changeGaming(null,{...proposal(),gameId:'unavailable'},gameContext(A),NOW),{code:'PURPOSE_GAME_UNAVAILABLE'})
})
